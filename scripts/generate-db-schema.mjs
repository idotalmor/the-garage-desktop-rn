/**
 * Generates each feature DB's `create-tables.generated.ts` from its Drizzle schema
 * (`drizzle-kit export`). Run `npm run db:generate` after changing a table, then Reset local data.
 * Statements get `IF NOT EXISTS` so opening the DB only creates missing tables (no migrations).
 */
import { execFileSync } from 'child_process'
import { writeFileSync } from 'fs'
import { dirname, join } from 'path'

const CONFIGS = [
  'src/main/local-repos/db/drizzle.config.ts',
  'src/main/git-sources/db/drizzle.config.ts'
]

for (const config of CONFIGS) {
  const sql = execFileSync('npx', ['drizzle-kit', 'export', '--config', config], {
    encoding: 'utf8'
  })
    .split('\n')
    .filter(
      (line) => line.trim() && !line.startsWith('--') && !line.includes('statement-breakpoint')
    )
    .join('\n')
    .replaceAll('`', '"')
    .replace(/CREATE TABLE "/g, 'CREATE TABLE IF NOT EXISTS "')
    .replace(/CREATE (UNIQUE )?INDEX "/g, 'CREATE $1INDEX IF NOT EXISTS "')
  const out = join(dirname(config), 'create-tables.generated.ts')
  writeFileSync(
    out,
    `/** Generated by \`npm run db:generate\` from \`schema.ts\`. Do not edit. */\nexport const CREATE_TABLES_SQL = \`\n${sql}\n\`\n`
  )
  console.log('wrote', out)
}
