/**
 * Opens a feature's SQLite file, `~/.devflow/<name>.db`, on first use and wraps it with Drizzle:
 * creates the folder, sets the pragmas, creates missing tables and closes it on quit. No migrations:
 * tables that already exist are left as they are; `resetDb` drops everything and creates the
 * current tables again.
 */
import { app } from 'electron'
import { existsSync, mkdirSync } from 'fs'
import { join } from 'path'
import Database from 'better-sqlite3'
import { drizzle, type BetterSQLite3Database } from 'drizzle-orm/better-sqlite3'

export type SqliteDatabase<TSchema extends Record<string, unknown>> = {
  /** The Drizzle handle (opened on the first call). The raw `better-sqlite3` connection is `$client`. */
  getDb: () => BetterSQLite3Database<TSchema> & { $client: Database.Database }
  /** Drops every table in the file and creates the current ones again, empty. */
  resetDb: () => void
}

export function openDatabase<TSchema extends Record<string, unknown>>(
  name: string,
  options: {
    /** The feature's tables and relations (`import * as schema from './schema'`). */
    schema: TSchema
    /** `CREATE TABLE IF NOT EXISTS …` for every table, generated by `npm run db:generate`. */
    createTablesSql: string
  }
): SqliteDatabase<TSchema> {
  let db: ReturnType<SqliteDatabase<TSchema>['getDb']> | null = null

  const getDb = (): ReturnType<SqliteDatabase<TSchema>['getDb']> => {
    if (db) return db
    const dir = join(app.getPath('home'), '.devflow')
    if (!existsSync(dir)) mkdirSync(dir, { recursive: true })

    const client = new Database(join(dir, `${name}.db`))
    client.pragma('journal_mode = DELETE')
    client.pragma('foreign_keys = ON')
    client.exec(options.createTablesSql)
    db = drizzle({ client, schema: options.schema })

    app.on('before-quit', () => client.close())
    return db
  }

  const resetDb = (): void => {
    const client = getDb().$client
    const tables = client
      .prepare("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'")
      .pluck()
      .all() as string[]
    client.pragma('foreign_keys = OFF')
    try {
      client.transaction(() => {
        for (const table of tables) client.exec(`DROP TABLE IF EXISTS "${table}"`)
        client.exec(options.createTablesSql)
      })()
    } finally {
      client.pragma('foreign_keys = ON')
    }
  }

  return { getDb, resetDb }
}
